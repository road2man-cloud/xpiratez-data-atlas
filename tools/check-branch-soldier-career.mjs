import assert from "node:assert/strict";
import fs from "node:fs";
import {gunzipSync} from "node:zlib";
import {buildCareerMedalPlan} from "../public/branch-soldier-career.js";
const db=JSON.parse(gunzipSync(fs.readFileSync("public/data/branch-soldier-results.json.gz")));
const modern=JSON.parse(fs.readFileSync("public/data/soldiers-modern-index.json","utf8"));
assert.equal(db.sourceMetadataSha256,modern.meta.source.metadataSha256);
const all=Object.values(db.witnesses).filter(w=>w.source==="CAREER12").map(w=>({w,p:buildCareerMedalPlan(w,modern,db.stats)}));
const f=all.find(({p})=>p.rows.length===4&&p.combined&&p.rows.some(r=>r.id==="STR_MEDAL_PIRATE_NAME"));
assert(f,"Fusion route must remain linked");
assert.deepEqual(f.p.delta,[2,1,1,0,2,0,1,1,0,0,1,10]);
assert.equal(f.p.rows.find(r=>r.id==="STR_MEDAL_NINJA_NAME").bonus[2],-1);
assert.deepEqual(f.p.combined,f.w.vector.map((n,i)=>n+f.p.delta[i]));
const r=all.find(({p})=>p.rows.length===1&&p.rows[0].id==="STR_MEDAL_STATGAIN_NAME"&&p.combined);
assert(r,"Red Knight route must remain linked");
assert.deepEqual(r.p.delta,[0,2,2,0,0,0,0,0,0,0,0,0]);
const repeated={...r.w,steps:[...r.w.steps,{id:"STR_RED_KNIGHT",count:1}]};
const repeat=buildCareerMedalPlan(repeated,modern,db.stats);
assert.equal(repeat.rows.length,1);
assert.deepEqual(repeat.delta,r.p.delta);
assert.equal(repeat.rows[0].milestones.length,2);
assert.equal(buildCareerMedalPlan({...r.w,medalBonusesExcluded:false},modern,db.stats).combined,null);
const clone={...r.w,steps:[...r.w.steps,{id:"STR_CHORT_SUMMONING"}]};
assert.equal(buildCareerMedalPlan(clone,modern,db.stats).combined,null);
assert(all.every(({p})=>p.actualGameCertified===false&&p.actualCareerReplayed===false));
console.log("PASS career medal worksheets:",JSON.stringify({careerWitnesses:all.length,medalRoutes:all.filter(x=>x.p.rows.length).length,conditionalOverlay:all.filter(x=>x.p.combined&&x.p.rows.length).length,unresolved:all.filter(x=>!x.p.complete).length}));
