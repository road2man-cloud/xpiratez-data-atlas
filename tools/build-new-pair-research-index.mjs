// Ordered research and treatment sets from independently registered pair careers.
// Each set points to actual full-action route witnesses; no unordered union is
// treated as a reachable research history, and no set implies a final optimum.
import fs from "node:fs";
import z from "node:zlib";
import assert from "node:assert/strict";
import {createHash} from "node:crypto";
import {createEventSeeds} from "./population-new-pair-event-seeds.mjs";
const key=x=>createHash("sha256").update(JSON.stringify(x)).digest("hex");
const db=JSON.parse(z.gunzipSync(fs.readFileSync("public/data/branch-soldier-results.json.gz"))),ledger=db.populationNewPairCareer,entry=db.populationNewPairEntry;
const data=JSON.parse(fs.readFileSync("public/data/soldiers-modern-index.json")),rules=new Map(data.transformations.map(r=>[r.id,r]));
assert.equal(data.meta.source.metadataSha256,db.sourceMetadataSha256);
const ev=createEventSeeds(db),kinds=new Set(["research","repeatResearch","freeResearch","eventResearch","missionResearch"]);
const nodes=[{parent:null,action:null}],edges=new Map(),histories={},routes={},transformGates={},sets={};
let researchSteps=0,gateCount=0;
function getBirth(r){
 const s=entry.routes[r.seed];if(s){const root=entry.roots[s.root];assert(root);return [...root.actions,...(s.actions.at(-1)?.type==="conditionalCapGrowth"?s.actions.slice(0,-1):s.actions)];}
 const e=ev.routes[r.seed];assert(e);return e.actions;
}
for(const [id,r] of Object.entries(ledger.routes)){
 assert(db.witnesses[id]&&r.actualGameCertified===false);
 const full=[...getBirth(r),...r.actions];assert.equal(key(full),r.fullActionHash);
 let node=0;const gates=[],contextIndices=[],researchIds=new Set();
 for(let i=0;i<full.length;i++){
  const a=full[i];
  if(kinds.has(a.type)){
   researchSteps++;const k=key([node,a]);let n=edges.get(k);
   if(n===undefined){n=nodes.length;edges.set(k,n);nodes.push({parent:node,action:a});}
   node=n;const rid=a.research||a.id;if(rid)researchIds.add(rid);
  }else{
   contextIndices.push(i);
   if(a.type==="transform"){
    const rule=rules.get(a.transform);assert(rule);
    const g={index:i,prefix:node,transform:a.transform,requires:rule.requires};gates.push(g);gateCount++;
    const k=key([r.branch,node,a.transform]),v=transformGates[k]??={branch:r.branch,prefix:node,transform:a.transform,requires:rule.requires,witnesses:[]};v.witnesses.push([id,i]);
   }
  }
 }
 const history=key([r.branch,node]),h=histories[history]??={branch:r.branch,prefix:node,explicitResearchIds:[...researchIds].sort(),routes:[]};h.routes.push(id);
 const transforms=[...new Set(gates.map(g=>g.transform))].sort(),set=key([r.branch,transforms]);
 const s=sets[set]??={branch:r.branch,transforms,historyRoutes:{}};(s.historyRoutes[history]??=[]).push(id);
 routes[id]={origin:r.origin,branch:r.branch,seed:r.seed,history,prefix:node,set,fullActionHash:r.fullActionHash,actionCount:full.length,contextIndices,transformGates:gates,actualGameCertified:false};
}
const summary={routeCount:Object.keys(routes).length,historyCount:Object.keys(histories).length,setCount:Object.keys(sets).length,matchedSets:Object.values(sets).filter(s=>Object.keys(s.historyRoutes).length).length,crossOriginHistories:Object.values(histories).filter(h=>new Set(h.routes.map(id=>routes[id].origin)).size>1).length,sharedSets:Object.values(sets).filter(s=>new Set(Object.values(s.historyRoutes).flat().map(id=>routes[id].origin)).size>1).length,researchSteps,uniqueResearchPrefixes:nodes.length-1,sharedPrefixSteps:researchSteps-(nodes.length-1),gateCount,uniqueGateGroups:Object.keys(transformGates).length,maxDistinctTransforms:Math.max(0,...Object.values(sets).map(s=>s.transforms.length)),actualGameCertified:0};
const index={schema:"CONDITIONAL_RESEARCH_WITNESS_INDEX_V1",sourceMetadataSha256:db.sourceMetadataSha256,sourceLedgerHash:key(Object.entries(ledger.routes).map(([id,r])=>[id,r.fullActionHash])),scope:"NEW_PAIR_CAREER: exact ordered research actions with actual full-action routes and transformation gate positions; conditional, not final certification",summary,nodes,histories,routes,transformGates,sets};
const file="soldier-new-pair-research-index.json.gz",bytes=z.gzipSync(Buffer.from(JSON.stringify(index)),{level:6});
fs.writeFileSync("public/data/"+file+".tmp",bytes);fs.renameSync("public/data/"+file+".tmp","public/data/"+file);
fs.writeFileSync("public/branch-soldier-new-pair-research-summary.js","// Generated by tools/build-new-pair-research-index.mjs\nexport const newPairResearchSummary="+JSON.stringify({...summary,file,sourceLedgerHash:index.sourceLedgerHash,sha256:createHash("sha256").update(bytes).digest("hex")})+";\n");
console.log(JSON.stringify({...summary,bytes:bytes.length}));
