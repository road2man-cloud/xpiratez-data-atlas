import assert from 'node:assert/strict';
import {advanceGrowthDistribution,conditionalGrowthProjection,thresholdProbability} from '../public/soldiers/modern/conditional-growth-math.js';
const p=advanceGrowthDistribution([[9,1]],{attempts:2,cap:10,kernel:[[0,0.5],[1,0.5]]});
assert.deepEqual(p.distribution,[[9,0.25],[10,0.75]]);
assert.equal(p.expected,9.75);
assert.deepEqual(advanceGrowthDistribution([[10,1]],{attempts:3,cap:10,kernel:[[2,1]]}).distribution,[[10,1]]);
assert.deepEqual(advanceGrowthDistribution([[9,1]],{attempts:2,cap:10,kernel:[[2,1]]}).distribution,[[11,1]]);
assert.deepEqual(advanceGrowthDistribution([[12,1]],{attempts:2,cap:10,kernel:[[1,1]]}).distribution,[[12,1]]);
assert.deepEqual(advanceGrowthDistribution([[12,1]],{attempts:2,cap:10,bonus:3,kernel:[[1,1]]}).distribution,[[13,1]]);
assert.equal(thresholdProbability(p.distribution,10),0.75);
assert.throws(()=>advanceGrowthDistribution([[8,1]],{attempts:2,cap:10}),/커널/);
assert.throws(()=>advanceGrowthDistribution([[8,1]],{attempts:2,cap:10,kernel:[[1,0.7]]}),/커널/);
assert.throws(()=>advanceGrowthDistribution([[8,1]],{attempts:-1,cap:10,kernel:[[1,1]]}),/횟수/);
const roll={distributions:{tu:[[9,1]],stamina:[[20,1]]}};
const incomplete=conditionalGrowthProjection(roll,{tu:{attempts:1,cap:10,kernel:[[1,1]]}});
assert.equal(incomplete.kind,'incomplete-scenario');
assert.ok(incomplete.skipped.includes('stamina'));
assert.equal(incomplete.expectedTotal,undefined);
console.log('conditional growth: 12 assertions passed');
