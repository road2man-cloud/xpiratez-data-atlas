import assert from "node:assert/strict";
import {latestRecruitmentAttempt,canRetryRecruitment,runnableDonorWindow,bestRecruitmentJob} from "./population-recruitment-pair-queue.mjs";
const fail={status:"LIMITED_UNRESOLVED",variant:2},partial={status:"PARTIAL_RESEARCH",variant:3,stage:"prefix"},success={status:"CONDITIONAL_REPLAY",variant:0};
assert.equal(latestRecruitmentAttempt(fail,{variant:1}),fail);
assert.equal(latestRecruitmentAttempt(fail,partial),partial);
assert.equal(latestRecruitmentAttempt(partial,success),success);
assert.equal(latestRecruitmentAttempt(success,partial),success);
assert.equal(canRetryRecruitment(fail),false);
assert.equal(canRetryRecruitment(partial),true);
assert.equal(canRetryRecruitment(undefined),true);
assert.equal(canRetryRecruitment(success),false);
const ds=Array.from({length:32},(_,id)=>({id,possible:["a","b"]}));
const eligible=(d,p)=>d.id>=24||d.id===23&&p==="b";
const cmp=(a,b)=>a.id-b.id;
const w=runnableDonorWindow(ds,eligible,cmp,8);
assert.deepEqual(w.donors.map(d=>d.id),[23,24,25,26,27,28,29,30]);
assert.deepEqual(w.donors[0].possible,["b"]);
assert.equal(w.exhausted,23);
assert.equal(w.deferred,1);
assert.equal(ds[23].possible.length,2);
assert.equal(runnableDonorWindow(ds,()=>false,cmp,8).donors.length,0);
const turns={a:0,b:0},jobs=[{id:0,p:"a",priority:3},{id:1,p:"a",priority:2},{id:2,p:"b",priority:1}];
const compare=(a,b)=>turns[a.p]-turns[b.p]||b.priority-a.priority||a.id-b.id;
const used=new Set();
let j=bestRecruitmentJob(jobs,x=>!used.has(x.id),compare);
assert.equal(j.id,0);used.add(j.id);turns[j.p]++;
j=bestRecruitmentJob(jobs,x=>!used.has(x.id),compare);
assert.equal(j.id,2);used.add(j.id);turns[j.p]++;
assert.equal(bestRecruitmentJob(jobs,x=>!used.has(x.id),compare).id,1);
assert.equal(bestRecruitmentJob(jobs,()=>false,compare),undefined);
assert.throws(()=>runnableDonorWindow(ds,eligible,cmp,0));
console.log("recruitment pair queue: 19 assertions passed");
