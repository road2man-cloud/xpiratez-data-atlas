import fs from 'node:fs';
import {gunzipSync} from 'node:zlib';
import {createHash} from 'node:crypto';
import {foundationWorld} from '../public/soldiers/modern/origin-witness.js';
import {auditOriginCampaignContext} from '../public/soldiers/modern/origin-campaign-context.js';
import {member} from './population-growth-replay-core.mjs';
import {createCareerReplay} from './population-chronological-career-core.mjs';
import {defaultRankData,RANK_POLICY} from './population-frontier-default-rank.mjs';
import {createResearchMaterialPolicy} from './atlas-research-material-policy.mjs';
import {produceOvercapIntegratedReplay} from '../public/branch-soldier-overcap-integrated-replay.js';
const read=p=>JSON.parse(fs.readFileSync(p));
const inputs={runtime:'public/data/soldiers-modern-index.json.gz',queue:'public/data/soldier-overcap-research-queue.json',contextResearch:'public/data/soldier-overcap-context-research-v2.json',originEvidence:'public/data/soldier-acquisition-progression-20261102.json',materialIndex:'public/items/acquisition-index.json',branches:'public/data/soldier-atlas-career-branches.json'};
const blob=p=>{const b=fs.readFileSync(p);return createHash('sha1').update('blob '+b.length+'\0').update(b).digest('hex');};
const sourceBlobs=Object.fromEntries(Object.entries(inputs).map(([k,p])=>[k,blob(p)]));
const data=JSON.parse(gunzipSync(fs.readFileSync(inputs.runtime)));
const origin=read(inputs.originEvidence);
if(origin.sourceVersion!=='v.o2')throw Error('Origin source mismatch');
data.originRows=origin.rows;data.sourceItemIds=new Set(read('public/data/soldier-source-catalog.json').itemIds);
const queue=read(inputs.queue),prep=read(inputs.contextResearch),branches=read(inputs.branches),acq=read(inputs.materialIndex);
const rank=defaultRankData(data),material=createResearchMaterialPolicy(rank.data,{acquisition:acq});
const output=produceOvercapIntegratedReplay(rank.data,queue,prep,branches,{createCareerReplay,foundationWorld,auditOriginCampaignContext,member},material,{sourceBlobs,rankPolicy:{policy:RANK_POLICY,indexed:rank.indexed},materialSourceVersion:acq.meta.sourceVersion});
fs.writeFileSync('public/data/soldier-overcap-integrated-replay.json',JSON.stringify(output)+'\n');
console.log(JSON.stringify(output.summary));
