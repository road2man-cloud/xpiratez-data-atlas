import assert from "node:assert/strict";
import fs from "node:fs";
import {gunzipSync} from "node:zlib";
import {loadCareerRows,loadExplorationRows} from "../public/branch-soldier-atlas-career-core.js";
import {unifyCareerRows,groupUnifiedRows,rowStatus,unifiedStatusRows} from "../public/branch-soldier-unified-career-core.js";
const read=p=>JSON.parse(fs.readFileSync(p));
const modern=read("public/data/soldiers-modern-index.json");
const registry=JSON.parse(gunzipSync(fs.readFileSync("public/data/branch-soldier-results.json.gz")));
globalThis.fetch=async url=>new Response(fs.readFileSync(url));
const c=await loadCareerRows(modern,registry,{includeWitnesses:true}),e=await loadExplorationRows(modern,registry);
assert.deepEqual(c.errors,[]);assert.deepEqual(e.errors,[]);
const birth=modern.profiles.map(p=>({key:"birth:"+p.id,origin:p.id,body:p.soldierType,birthOnly:true}));
const all=unifyCareerRows(c.rows,e.rows,birth);
assert.equal(all.length,new Set(all.map(r=>r.key)).size);
assert.equal(unifiedStatusRows(all,"complete").length,c.rows.length);
assert.equal(unifiedStatusRows(all,"birth").length,modern.profiles.length);
for(const r of c.rows)assert.equal(all.find(q=>q.key===r.key),r);
const grouped=groupUnifiedRows(all,"origin");
assert.equal(new Set(grouped.map(r=>JSON.stringify([rowStatus(r),r.origin,r.body==="STR_SOLDIER_CHORT"]))).size,grouped.length);
assert(grouped.some(r=>r.complete));assert(grouped.some(r=>rowStatus(r)==="conditional"));
const firstPartial=grouped.findIndex(r=>!r.complete);assert(grouped.slice(firstPartial).every(r=>!r.complete));
console.log(JSON.stringify({complete:c.rows.length,exploration:e.rows.length,unified:all.length,birth:birth.length,representatives:grouped.length}));
